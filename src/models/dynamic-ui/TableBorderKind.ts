/**
 * The lines that separate a table's cells.
 *
 * - `'grid'`: lines around every cell.
 * - `'rows'`: lines between the rows only.
 * - `'none'`: no lines, e.g. for a list that is read down rather than across, such as a navigation's links.
 */
export type TableBorderKind = 'grid' | 'rows' | 'none'
